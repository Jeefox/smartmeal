export function makeDemoRecipe(
  data: Omit<Recipe, 'ingredients'> & { ingredients: { productId: number; quantityG: number }[] },
): Recipe {
  const ingredients = data.ingredients.map((item, index) => ({
    ...item,
    productName: demoProducts.find((p) => p.id === item.productId)?.name || 'Продукт',
    position: index + 1,
  }));
  const total = ingredients.reduce(
    (sum, item) => {
      const p = demoProducts.find((p) => p.id === item.productId)!;
      return {
        calories: sum.calories + (p.caloriesPer100g * item.quantityG) / 100,
        protein: sum.protein + (p.proteinPer100g * item.quantityG) / 100,
        fat: sum.fat + (p.fatPer100g * item.quantityG) / 100,
        carbs: sum.carbs + (p.carbsPer100g * item.quantityG) / 100,
      };
    },
    { calories: 0, protein: 0, fat: 0, carbs: 0 },
  );
  return {
    ...data,
    ingredients,
    nutritionTotal: total,
    nutritionPerServing: {
      calories: total.calories / data.servings,
      protein: total.protein / data.servings,
      fat: total.fat / data.servings,
      carbs: total.carbs / data.servings,
    },
  };
}
