package dev.jeefox.smartmeal.auth.config;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import java.util.*;

@Component
public final class CatalogueEditors {
    private final Set<UUID> ids;

    public CatalogueEditors(@Value("${smartmeal.security.catalogue-editor-ids:}") String value) {
        var result = new HashSet<UUID>();
        for (String part : value.split(",")) {
            if (part.isBlank()) continue;
            String id = part.trim();
            if (!id.matches(
                    "[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"))
                throw new IllegalArgumentException(
                        "Catalogue editor configuration must contain account UUIDs");
            result.add(UUID.fromString(id));
        }
        ids = Set.copyOf(result);
    }

    // UUIDs are generated by the server; an unverified email never grants privileges.
    public boolean contains(UUID userId) {
        return ids.contains(userId);
    }
}
